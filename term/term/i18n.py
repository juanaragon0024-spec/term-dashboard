def translate(lang: str, key: str, /, **kwargs: object) -> str:
    """Cadena traducida para `lang`, con reserva a espanol y luego a la clave.

    `lang` y `key` son posicionales-only a proposito: hay cadenas que llevan un
    marcador {lang}, y si el parametro fuese nombrado chocaria con el.

    Un `format` fallido devuelve la plantilla sin interpolar en lugar de
    reventar: una traduccion con un marcador mal escrito no debe tumbar la TUI.
    """
    strings = TRANSLATIONS.get(lang, TRANSLATIONS[DEFAULT_LANG])
    text = strings.get(key) or TRANSLATIONS[DEFAULT_LANG].get(key) or key
    if kwargs:
        with contextlib.suppress(KeyError, IndexError, ValueError):
            text = text.format(**kwargs)
    return text


